import path from 'node:path';
import { promises as fs } from 'node:fs';
import { RETIRED_SINK_DIRS, type ToolDef, type SkillSink } from '../adapters/index.js';
import { pathExists, readFileSafe, listIfPresent } from '../core/project.js';

/**
 * Remove generated carriers that no longer have a canonical skill behind them.
 *
 * Two cases, one rule: **only a file engram itself generated is ever deleted.**
 *
 * 1. A sink directory engram retired (`.pi/skills`): the four copies engram used to write are
 *    orphans in every repository that ever ran `sync`.
 * 2. A skill the project deleted from `.ai/skills/`. Without this, `sync` refreshed the surviving
 *    carriers and left the deleted one advertising itself to the tool forever — the tool then
 *    offers a `/skill` command whose canonical spec is gone, and nothing reports it.
 *
 * Hand-written files are out of reach: `research/.agents/skills/net-access/SKILL.md` carries no
 * generated header, so a project-owned skill sitting in a carrier directory survives every sync.
 * `.ai/` is never a carrier dir, so the canonical bank cannot be touched here at all.
 */

/**
 * The generated header, matched as a **whole line** — never as a substring.
 *
 * `content.includes('<!-- engram:generated -->')` looked equivalent and was not: a hand-written
 * carrier whose prose *mentions* the marker — a `.claude/skills/engram-notes/SKILL.md` explaining
 * how carriers are stamped, say — was classified as generated and deleted, which is the exact
 * opposite of what the docstring above promises. Requiring the rest of the stamp (`generated by
 * engram from <path>`) means even a quoted line does not qualify.
 */
const GENERATED_HEADER_RE = /^<!-- engram:generated --> generated by engram from \S+/m;

async function isGeneratedCarrier(root: string, rel: string): Promise<boolean> {
  const content = await readFileSafe(path.join(root, rel));
  return content !== null && GENERATED_HEADER_RE.test(content);
}

/**
 * Resolve a path and confirm it is still inside the project root.
 *
 * `pathExists`, `readFileSafe` and `fs.rm` all follow symlinks, so a symlinked carrier directory
 * pointing outside the repository let pruning delete a file engram never created. The *parent*
 * directory is what gets resolved — the leaf is the file being tested, and on some paths it may not
 * exist yet.
 */
async function resolvesInside(root: string, rel: string): Promise<boolean> {
  try {
    const realRoot = await fs.realpath(root);
    const realParent = await fs.realpath(path.dirname(path.join(root, rel)));
    return realParent === realRoot || realParent.startsWith(realRoot + path.sep);
  } catch {
    // Unresolvable (missing parent, ELOOP, EACCES): treat as unsafe rather than guess.
    return false;
  }
}

/** Carrier paths the given tools write. A dir in here is never treated as retired. */
function ownedDirs(tools: ToolDef[]): Set<string> {
  return new Set(tools.flatMap((t) => t.skillSinks.map((s) => s.dir)));
}

async function removeIfEmpty(dir: string): Promise<void> {
  try {
    const entries = await fs.readdir(dir);
    if (entries.length === 0) await fs.rmdir(dir);
  } catch {
    // A non-empty or already-gone directory is the normal case.
  }
}

export interface PruneResult {
  /** Carrier paths that were removed, project-relative. */
  removed: string[];
}

/** Every generated carrier file present in one sink directory, including nested `SKILL.md`. */
async function carriersIn(root: string, sink: SkillSink): Promise<string[]> {
  const abs = path.join(root, sink.dir);
  const listing = await listIfPresent(abs);
  const out = listing.names.map((entry) => path.posix.join(sink.dir, entry));
  if (sink.kind !== 'agent-skills') return out;
  // `agent-skills` also nests `<name>/SKILL.md`; a file listing alone cannot see it.
  try {
    for (const dirent of await fs.readdir(abs, { withFileTypes: true })) {
      if (dirent.isDirectory()) out.push(path.posix.join(sink.dir, dirent.name, 'SKILL.md'));
    }
  } catch {
    /* absent or unreadable: nothing to prune */
  }
  return out;
}

/** The skill name a carrier path was generated for, or null when the shape is unrecognised. */
function nameOfCarrier(sink: SkillSink, rel: string): string | null {
  const base = path.posix.basename(rel);
  if (sink.kind === 'agent-skills') {
    return base === 'SKILL.md' ? path.posix.basename(path.posix.dirname(rel)) : base.replace(/\.md$/, '');
  }
  // `prompt-md-args` is the only other carrier shape: `<name>.md`.
  return base.endsWith('.md') ? base.slice(0, -'.md'.length) : null;
}

/**
 * Every file inside a retired sink dir, including one level of `<name>/SKILL.md` nesting.
 *
 * `listIfPresent` returns files only, so the nested shape needs its own pass — the same reason
 * `carriersIn` exists for live sinks.
 */
async function carriersInRoot(root: string, dir: string, names: readonly string[]): Promise<string[]> {
  const out = names.map((n) => path.posix.join(dir, n));
  try {
    for (const entry of await fs.readdir(path.join(root, dir), { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const nested = path.posix.join(dir, entry.name, 'SKILL.md');
      if (await pathExists(path.join(root, nested))) out.push(nested);
    }
  } catch {
    /* unreadable or absent: nothing to prune */
  }
  return out;
}

/**
 * Remove generated carriers whose canonical skill is gone, plus everything left behind in a
 * retired sink directory. Returns the removed paths; never touches a file it did not generate.
 *
 * `canonicalNames` being empty is **not** treated as "no skills exist, delete everything". An empty
 * list can also mean the caller could not read the canonical directory — a missing `.ai/skills/`, a
 * `--root` typo, a bank mid-move, an unreadable directory — and in that state deleting every
 * carrier is the worst available guess. When the canonical directory is gone the carriers are the
 * *only* copy of each skill body, so the loss is real and unrecoverable.
 *
 * That is why the signature demands an explicit `skillsDirAuthoritative` rather than inferring
 * intent from a count. A default of `true` is deliberately the *unsafe* value: every caller must
 * state the precondition, and the compiler makes it awkward to forget.
 */
export async function pruneStaleCarriers(
  root: string,
  tools: ToolDef[],
  canonicalNames: readonly string[],
  options: { dryRun?: boolean; skillsDirAuthoritative?: boolean } = {},
): Promise<PruneResult> {
  const { dryRun = false, skillsDirAuthoritative = false } = options;
  const owned = ownedDirs(tools);
  const removed: string[] = [];
  const canonical = new Set(canonicalNames);
  // Without a readable canonical directory there is no authority to declare a carrier an orphan.
  const pruneOrphans = skillsDirAuthoritative;

  // 1. Retired sink dirs. `owned` is the guard: a dir a current tool claims is live, whatever this
  //    list says.
  //
  //    This used to enumerate `${SKILL_SPECS.name}` × three hard-coded filename shapes, because "only
  //    engram's own built-in names were ever written there". That was already fragile and it silently
  //    broke the day a retired client's carrier had a fourth shape: Copilot's prompt files are
  //    `<name>.prompt.md`, which matched none of the three, so `.github/prompts/*.prompt.md` survived
  //    every `sync` in every repository that had ever used that adapter. Enumerating the directory
  //    instead means a retired dir is cleaned whatever shape its files have — the safety property was
  //    never the name list, it is the generated-marker check below plus `resolvesInside`.
  for (const dir of RETIRED_SINK_DIRS) {
    if (owned.has(dir)) continue;
    const listing = await listIfPresent(path.join(root, dir));
    let touched = false;
    for (const rel of await carriersInRoot(root, dir, listing.names)) {
      if (!(await resolvesInside(root, rel))) continue;
      if (!(await isGeneratedCarrier(root, rel))) continue;
      if (!dryRun) await fs.rm(path.join(root, rel));
      removed.push(rel);
      touched = true;
      // A `<name>/SKILL.md` carrier leaves its now-empty directory behind.
      if (rel.endsWith('/SKILL.md')) await removeIfEmpty(path.join(root, path.posix.dirname(rel)));
    }
    if (touched && !dryRun) await removeIfEmpty(path.join(root, dir));
  }

  // 2. Orphans in the sinks the selected tools do own: a carrier whose canonical spec is gone.
  //    Enumerating the directory (not a name list) is what catches a skill deleted outright —
  //    its name is not in any list this process was handed.
  if (pruneOrphans) {
    for (const tool of tools) {
      for (const sink of tool.skillSinks) {
        for (const rel of await carriersIn(root, sink)) {
          const name = nameOfCarrier(sink, rel);
          if (!name || canonical.has(name)) continue;
          if (!(await resolvesInside(root, rel))) continue;
          if (!(await isGeneratedCarrier(root, rel))) continue;
          if (!dryRun) await fs.rm(path.join(root, rel));
          removed.push(rel);
          if (!dryRun && rel.endsWith('SKILL.md')) await removeIfEmpty(path.join(root, sink.dir, name));
        }
      }
    }
  }

  return { removed: [...new Set(removed)] };
}
