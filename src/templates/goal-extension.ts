/**
 * The pi goal extension, generated as source.
 *
 * Why generated source rather than a compiled import: `.pi/extensions/*.ts` is loaded by pi's own
 * loader from inside the *user's* repository. It cannot resolve `@zeroicey/engram/build/…`, and
 * giving it a bundled copy of the engine would mean two implementations of every rule. So the file
 * below holds **no rules at all** — it is a marshaller. Every decision is one `engram goal event
 * --json` call away, which is also why the file stays short enough to audit by reading.
 *
 * What it does own, because it is host mechanics and nothing else:
 *
 * - which pi lifecycle event maps to which `engram` event,
 * - `agent_before_settle` → `{ continue: true, entries: [...] }`, exactly once,
 * - the 85% context reminder, once per crossing,
 * - a `goal_report` tool whose arguments are validated by engram, not by a schema the model guesses
 *   around,
 * - `/goal` for a human.
 *
 * The output is **plain JavaScript-valid TypeScript**: no annotations, no imports beyond
 * `node:child_process`. That is deliberate — it means the emitted string can be syntax-checked with
 * `node --check`, which `test/goal-extension.test.ts` does, so a broken generated file cannot reach
 * a user's repository.
 *
 * Opt-in: `sync` only writes this when `.engram/config.json` says `goal.enabled` is true.
 */

export interface GoalExtensionContext {
  /** The `engram` command the generated file should call (`engram` on PATH by default). */
  engramBin: string;
  /** Recorded so a reader can tell which version generated the file. */
  version: string;
}

export const GOAL_EXTENSION_PATH = '.pi/extensions/engram-goal.ts';

/** The first line `sync` matches before it is allowed to replace or remove the file. */
export const GOAL_EXTENSION_HEADER = '// generated by engram';

export function goalExtensionSource(ctx: GoalExtensionContext): string {
  return `${GOAL_EXTENSION_HEADER} @zeroicey/engram@${ctx.version} — edit .ai/ and run \'engram sync\' instead.
//
// This file holds no goal rules. It maps pi lifecycle events onto \'engram goal event --json\' and
// applies the answer. Every decision (what continues, what waits, what counts as done) lives in
// engram's core, so there is exactly one implementation and this file cannot drift from it.
//
// Opt-in: remove "goal" from .engram/config.json and run \'engram sync\' to delete this file.

import { spawnSync } from "node:child_process";

// ENGRAM_BIN wins at run time so a development checkout (and a machine where engram is not on PATH)
// can point the extension at a binary without regenerating the file.
const ENGRAM = process.env.ENGRAM_BIN || ${JSON.stringify(ctx.engramBin)};

const CONTEXT_REMINDER =
  "Context is above 85%. If this is a clean delivery point, consider goal_report(status='handoff') " +
  "and let a successor session take the baton. If it is not, keep working — this is a reminder, not a stop.";

/**
 * One CLI call. spawnSync with an argv array (never a shell string), so a reason containing a quote
 * or a newline cannot turn into a second command.
 */
let unreachable = false;
function call(args) {
  const res = spawnSync(ENGRAM, args, {
    encoding: "utf8",
    timeout: 11 * 60 * 1000,
    stdio: ["ignore", "pipe", "pipe"],
  });
  // A missing binary, a crash, and a non-zero exit with no stdout are the same *loud* state: silently
  // doing nothing is how a goal engine looks installed while every settlement goes unrecorded. The
  // empty-stdout case is the gap a crash slipped through.
  //
  // The timeout exceeds the evaluator's: 'event --type report' runs done_when inside the CLI (10 min
  // for a cmd gate), so a 30 s host bound SIGTERMed the child mid-gate and the report was lost.
  const out = (res.stdout || "").trim();
  if (res.error || res.status === null || (res.status !== 0 && out === "")) {
    unreachable = true;
    return null;
  }
  if (!out) return null;
  const line = out.split("\\n").find((l) => l.startsWith("{")) || out;
  try {
    return JSON.parse(line);
  } catch (e) {
    return null;
  }
}

function warnUnreachable(pi) {
  if (!unreachable || warned) return;
  warned = true;
  notify(
    pi,
    "engram-goal: cannot run " + ENGRAM + ". Set ENGRAM_BIN or put engram on PATH — the goal engine is not recording anything.",
  );
}

/**
 * This session's identity, for the baton check.
 *
 * The engine refuses an event that carries no identity when the goal already has a holder, and
 * scoping a goal to the *project* means two panes can be open on the same goal at once — so the
 * holder must be identified or neither session can drive and the second silently wins. pi exposes the
 * session file through the context; 'undefined' is kept as 'undefined' so a goal with no baton yet
 * still accepts its first claimant.
 */
function identity(ctx) {
  try {
    return ctx && ctx.sessionManager && ctx.sessionManager.getSessionFile();
  } catch (e) {
    return undefined;
  }
}

function event(type, extra, ctx) {
  const args = ["goal", "event", "--type", type].concat(extra || []);
  const session = identity(ctx);
  if (session) args.push("--session", session);
  return call(args);
}

function notify(pi, text) {
  if (!text) return;
  pi.sendMessage({ customType: "engram-goal", content: text, display: true });
}

let warned = false;

export default function (pi) {
  // Once per threshold crossing; reset when the context drops back below it.
  let reminded = false;

  // A new run releases the wait latch inside engram. Doing this on agent_start (not before_settle)
  // is what makes "any new run resumes the loop" true, including a background-task completion and a
  // herdr agent prompt.
  pi.on("agent_start", (_event, ctx) => {
    const res = event("run-started", [], ctx);
    warnUnreachable(pi);
    notify(pi, res && res.notify);
  });

  // A wait that survived a pi restart is re-armed here, or escalated if its deadline passed.
  pi.on("session_start", (_event, ctx) => {
    const res = event("reconcile", [], ctx);
    warnUnreachable(pi);
    notify(pi, res && res.notify);
  });

  // The continuation guard. pi allows exactly one continuation per settlement; engram decides
  // whether this is that one. Returning nothing means "settle".
  pi.on("agent_before_settle", (_event, ctx) => {
    const res = event("settled", [], ctx);
    warnUnreachable(pi);
    if (!res || !res.continue || !res.message) {
      notify(pi, res && res.notify);
      return undefined;
    }
    return {
      continue: true,
      entries: [
        { type: "custom_message", customType: "engram-goal", content: res.message, display: true },
      ],
    };
  });

  // 85% is a reminder, never a handoff trigger: the agent judges whether this is a clean point.
  pi.on("turn_end", (_event, ctx) => {
    const usage = ctx && ctx.getContextUsage ? ctx.getContextUsage() : undefined;
    const percent = usage && typeof usage.percent === "number" ? usage.percent : null;
    if (percent === null || percent < 85) {
      reminded = false;
      return;
    }
    if (reminded) return;
    reminded = true;
    notify(pi, CONTEXT_REMINDER);
  });

  // The escape hatch: nothing else nudges while waiting, so an external wake must be deliverable.
  pi.registerCommand("goal", {
    description: "Show the active goal, or wake it: /goal wake <reason>",
    handler: async (args, ctx) => {
      const text = (args || "").trim();
      if (text.startsWith("wake")) {
        const reason = text.slice(4).trim() || "woken by a human";
        // The JSON channel, not the 'wake' verb: 'goal wake' prints human lines, so 'call()' — which
        // needs a line starting with '{' — returned null and told the human the wake failed *after*
        // it had already succeeded.
        const res = event("wake", ["--reason", reason], ctx);
        ctx.ui.notify(res ? res.notify || res.reason || "goal woken" : "engram goal wake failed", "info");
        return;
      }
      const res = event("status", [], ctx);
      ctx.ui.notify((res && (res.message || res.reason)) || "no active goal", "info");
    },
  });

  pi.registerTool({
    name: "goal_report",
    label: "Report on the active goal",
    description:
      "Report on the active long-running goal. Call once per turn, before the turn ends. " +
      "status=progress continues. status=wait parks the loop until something ends on its own " +
      "(needs wakeOnType plus wakeOnSeconds, wakeOnPid or wakeOnPath). status=blocked needs a human " +
      "(reason). status=done asks engram to verify done_when — a claim is not a verdict. " +
      "status=handoff opens a successor pane through herdr, hands it the baton and this session stops " +
      "driving — use it at a clean delivery point, not to escape a hard problem. If BRIEF.md declares " +
      "no done_when, declare one first or report blocked.",
    parameters: {
      type: "object",
      properties: {
        status: { type: "string", enum: ["progress", "wait", "blocked", "done", "handoff"] },
        note: { type: "string", description: "One line on what changed (progress/wait)." },
        wakeOnType: { type: "string", enum: ["time", "process", "artifact"] },
        wakeOnSeconds: { type: "number", description: "For wakeOnType=time." },
        wakeOnPid: { type: "number", description: "For wakeOnType=process." },
        wakeOnPath: { type: "string", description: "For wakeOnType=artifact." },
        reason: { type: "string", description: "Required for blocked; optional for handoff." },
        needs: { type: "string", description: "Who or what you need, for blocked." },
        claim: { type: "string", description: "Optional one-line claim, for done." },
      },
      required: ["status"],
    },
    async execute(_id, params, _signal, _onUpdate, ctx) {
      const args = ["goal", "event", "--type", "report", "--report", JSON.stringify(params)];
      const session = identity(ctx);
      if (session) args.push("--session", session);
      const res = call(args);
      if (!res) {
        // A hard failure is an error result, not prose in 'content': pi's contract says throw or set
        // 'isError', and a model reads plain content as success.
        return {
          content: [{ type: "text", text: "engram goal event failed (is engram installed and on PATH?)" }],
          details: undefined,
          isError: true,
        };
      }
      if (!res.ok) {
        // A validation message that names the right usage teaches the model in one turn; a bare
        // failure makes it guess.
        return { content: [{ type: "text", text: res.reason || "invalid goal report" }], details: undefined, isError: true };
      }
      const parts = ["goal " + (res.goalId || "") + ": " + (res.status || "?")];
      if (res.reason) parts.push(res.reason);
      if (res.notify) parts.push(res.notify);
      if (!res.continue && res.message) parts.push(res.message);
      // A handoff report is a *request*, not an action: pi's own session API cannot create a session
      // (upstream #2488), so the successor pane is opened through herdr — and only because the model
      // asked for the handoff in this very call. Nothing in the lifecycle decides to spawn.
      if (res.reason === "handoff requested") {
        const handed = call([
          "goal",
          "handoff",
          "--json",
          "--reason",
          String(params.reason || params.note || "context is filling"),
        ]);
        parts.push(
          handed && handed.message
            ? handed.message
            : "handoff was NOT taken — no successor pane was opened (is herdr present?)",
        );
      }
      return { content: [{ type: "text", text: parts.join("\\n") }], details: undefined };
    },
  });
}
`;
}
